-- NRW-Feiertage in DB + Verknüpfung Teammitglieder mit Auth-User

alter table team_kalender.team_members
  add column if not exists user_id uuid unique references auth.users(id) on delete set null;

create table if not exists team_kalender.nrw_holidays (
  id uuid primary key default gen_random_uuid(),
  holiday_date date not null,
  label text not null,
  created_at timestamptz default now() not null,
  constraint nrw_holidays_date_key unique (holiday_date)
);

alter table team_kalender.nrw_holidays disable row level security;

